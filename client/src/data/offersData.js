// Helper to intelligently resolve the high-res image for each item in an offer
export const resolveOfferItemImage = (itemTitle = '', itemIndex = 0, offer = {}, products = []) => {
  // 1. Check if offer has explicit itemImages array
  if (offer.itemImages && Array.isArray(offer.itemImages) && offer.itemImages[itemIndex]) {
    return offer.itemImages[itemIndex];
  }

  const cleanTitle = (itemTitle || '').toLowerCase();

  // 2. Search in store products
  if (Array.isArray(products) && products.length > 0) {
    const matchedProd = products.find((p) => {
      const prodName = (p.name || '').toLowerCase();
      return (
        cleanTitle.includes(prodName) ||
        prodName.includes(cleanTitle) ||
        (cleanTitle.includes('chatgpt') && prodName.includes('chatgpt')) ||
        (cleanTitle.includes('claude') && prodName.includes('claude')) ||
        (cleanTitle.includes('canva') && prodName.includes('canva')) ||
        (cleanTitle.includes('capcut') && prodName.includes('capcut')) ||
        (cleanTitle.includes('netflix') && prodName.includes('netflix')) ||
        (cleanTitle.includes('youtube') && prodName.includes('youtube')) ||
        (cleanTitle.includes('spotify') && prodName.includes('spotify')) ||
        (cleanTitle.includes('gemini') && prodName.includes('gemini')) ||
        (cleanTitle.includes('windows') && prodName.includes('windows'))
      );
    });

    if (matchedProd && matchedProd.images && matchedProd.images.length > 0) {
      return matchedProd.images[0];
    }
  }

  // 3. Fallback map for common popular digital subscriptions
  if (cleanTitle.includes('chatgpt') || cleanTitle.includes('gpt-4')) {
    return 'https://i.ibb.co/mrG6mWZt/chatgpt-PNG16-png.png';
  }
  if (cleanTitle.includes('claude')) {
    return 'https://i.ibb.co/nNkwbdgL/claude-logo-png-seeklogo-554540-png.png';
  }
  if (cleanTitle.includes('canva')) {
    return 'https://i.ibb.co/SXrYntpD/ttffb5spn9itofvedtkq-webp.webp';
  }
  if (cleanTitle.includes('capcut')) {
    return 'https://i.ibb.co/V0tbYyWx/jcvfi3zdolrovn0ulsjg-webp.webp';
  }
  if (cleanTitle.includes('netflix')) {
    return 'https://i.ibb.co/Zz0t6Kxd/ldatmykiufwkkfwppjzr-webp.webp';
  }
  if (cleanTitle.includes('youtube')) {
    return 'https://i.ibb.co/6RqDx0DT/sy1sxm0ta1mhad9ny6ga-webp.webp';
  }
  if (cleanTitle.includes('windows')) {
    return 'https://img.icons8.com/color/512/windows-11.png';
  }
  if (cleanTitle.includes('office') || cleanTitle.includes('word') || cleanTitle.includes('365')) {
    return 'https://img.icons8.com/color/512/microsoft-office-2019.png';
  }
  if (cleanTitle.includes('spotify')) {
    return 'https://i.ibb.co/wr2GDY2g/16381f7c2b21da49b1afb3529c46f41a-jpg.jpg';
  }
  if (cleanTitle.includes('prime') || cleanTitle.includes('amazon')) {
    return 'https://i.ibb.co/ZRK5WQc5/dblzcznxrvg8qcqikrkd-webp.webp';
  }
  if (cleanTitle.includes('coursera')) {
    return 'https://i.ibb.co/gbvnTPrD/Chat-GPT-Image-Sep-17-2026-05-57-08-PM-webp.webp';
  }

  // 4. Default to offer image or store logo
  return offer.image || '/images/logo.png';
};

const STORAGE_KEY_OFFERS = 'technotech_offers_cache';

export const getStoredOffers = () => {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_OFFERS);
    // If cache has never been initialized, use INITIAL_OFFERS
    if (raw === null || raw === undefined) return INITIAL_OFFERS;
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return INITIAL_OFFERS;
    
    // If cache is intentionally empty (user deleted all offers), return empty list!
    if (parsed.length === 0) return [];
    
    // Ensure existing cached offers have itemImages populated from INITIAL_OFFERS if missing
    return parsed.map((offer) => {
      const matchInitial = INITIAL_OFFERS.find((init) => init.id === offer.id);
      if (matchInitial && (!offer.itemImages || offer.itemImages.length === 0)) {
        return { ...offer, itemImages: matchInitial.itemImages };
      }
      return offer;
    });
  } catch {
    return [];
  }
};

export const saveStoredOffers = (offers) => {
  try {
    if (Array.isArray(offers)) {
      localStorage.setItem(STORAGE_KEY_OFFERS, JSON.stringify(offers));
    }
  } catch (e) {
    console.warn('Erreur de sauvegarde locale des offres :', e);
  }
};
